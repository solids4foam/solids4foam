#ifndef FieldSumOp_H
#define FieldSumOp_H

#include "Field.H"

// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

namespace Foam
{

    template<class Type>
    struct FieldSumOp
    {
        public:

        // Op function
        Field<Type> operator()
        (
            const Field<Type>& x, const Field<Type>& y
        ) const
        {
            return Field<Type>(x + y);
        }
    };

// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

} // End namespace Foam


// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

#endif

