def _flat(outputs):
    names, exprs = [], []
    for cname, lst in outputs:
        for i, e in enumerate(lst):
            names.append(f"{cname}[{i}]")
            exprs.append(e)
    return names, exprs


def write_header(path, funcs, params, law, tick=print, variant="full"):
    with open(path, "w") as fh:
        consts = f"// variant: {variant}\n" + "".join(f"constexpr double param_{k} = {float(v)!r};\n" for k, v in params.items())
        fh.write(HEADER.format(law=law, params=", ".join(f"{k}={v}" for k, v in params.items()), consts=consts))
        for name, argn, outputs in funcs:
            names, exprs = _flat(outputs)
            syms = [se.Symbol(a) for a in argn]
            reps, red = se.cse(exprs)
            sig = ", ".join(f"const double {a}" for a in argn)
            outs = ", ".join(f"double {c}[{len(l)}]" for c, l in outputs)
            fh.write(f"// {name}: {len(reps)} temporaries\n")
            fh.write(f"inline void {name}({sig}, {outs})\n{{\n")
            for (sym, e) in reps:
                fh.write(f"    const double {sym} = {se.ccode(e)};\n")
            for n, e in zip(names, red):
                fh.write(f"    {n} = {se.ccode(e)};\n")
            fh.write("}\n\n")
            tick(f"  {name}: {len(reps)} temporaries")
        fh.write("} // namespace mmsFsi\n#endif\n")
