#!/usr/bin/env python3
"""Run the opt-in ringAddedMass verification study in isolated case copies.

The ring starts undeformed with the velocity of its n = 2 (ovalling) mode and
vibrates freely. The driver measures the dry (in vacuo) and wet (fluid-loaded)
frequencies from the zero crossings of the ovalling displacement, and
compares the frequencies and the wet/dry ratio with the exact linear
solution in reference/ringAddedMass_verification_references.json.
"""

