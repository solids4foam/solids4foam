def build_specs(args: argparse.Namespace, reference: dict) -> list[dict]:
    exact = reference["exact"]
    study = reference["study"]
    levels = args.levels.split(",") if args.levels else list(reference["levels"])
    for level in levels:
        if level not in reference["levels"]:
            fail(f"Unknown level '{level}'; choose from {list(reference['levels'])}")
    if args.quick:
        quick = study["quick"]
        mesh_factors, time_steps = quick["meshFactors"], []
        steps, periods = quick["stepsPerPeriod"], quick["periods"]
        levels = [level for level in levels if level in quick["levels"]] \
            or quick["levels"]
        studies = {"main"}
    else:
        mesh_factors = study["meshFactors"]
        time_steps = study["timeSteps"]
        steps, periods = study["stepsPerPeriod"], study["periods"]
        studies = {"main", "solid", "coupling"} if args.study == "all" \
            else {args.study}

    specs: dict[str, dict] = {}

    def add(kind: str, solid: str, factor: int, n: int, level: str = "",
            coupling: str = "iqnils", group: str = "main") -> None:
        omega = exact["dry"]["omega"] if kind == "dry" \
            else exact["levels"][level]["omega"]
        spec = {"kind": kind, "level": level if kind == "wet" else "",
                "coupling": coupling if kind == "wet" else "",
                "solid": solid, "factor": factor, "steps": n,
                "periods": periods, "omega_exact": omega,
                "period": 2 * math.pi / omega}
        spec["name"] = case_name(spec)
        entry = specs.setdefault(spec["name"], spec)
        entry.setdefault("groups", set()).add(group)

    if "main" in studies:
        for factor in mesh_factors:
            add("dry", "highOrder", factor, steps)
            for level in levels:
                add("wet", "highOrder", factor, steps, level)
        for n in time_steps:
            add("dry", "highOrder", study["timeStudyFactor"], n)
            for level in levels:
                add("wet", "highOrder", study["timeStudyFactor"], n, level)
    if "solid" in studies:
        for factor in mesh_factors:
            add("dry", "standard", factor, steps, group="solid")
            for level in levels:
                add("wet", "standard", factor, steps, level, group="solid")
            add("dry", "highOrder", factor, steps, group="solid")
            for level in levels:
                add("wet", "highOrder", factor, steps, level, group="solid")
    if "coupling" in studies:
        factor = study["couplingStudyFactor"]
        add("dry", "highOrder", factor, steps, group="coupling")
        for level in levels:
            for coupling in ("iqnils", "robin"):
                add("wet", "highOrder", factor, steps, level, coupling,
                    group="coupling")
    for spec in specs.values():
        spec["groups"] = sorted(spec["groups"])
    return list(specs.values())


