def read_columns(path: Path, column: int) -> tuple[list[float], list[float]]:
    if not path.is_file():
        fail(f"Missing history {path}")
    times, values = [], []
    for line in path.read_text(errors="replace").splitlines():
        fields = line.split()
        if not fields or fields[0].startswith("#"):
            continue
        try:
            t, v = float(fields[0]), float(fields[column])
        except (ValueError, IndexError):
            fail(f"Malformed line in {path}: {line!r}")
        if not (math.isfinite(t) and math.isfinite(v)):
            fail(f"Non-finite value in {path}: {line!r}")
        if times and t <= times[-1]:
            fail(f"Non-increasing time in {path} at t = {t}")
        times.append(t)
        values.append(v)
    return times, values


def read_histories(case: Path, spec: dict) -> tuple[list[float], list[float]]:
    """Ovalling displacement (u_r(0) - u_r(pi/2))/2, which removes any
    breathing (n = 0) component; checks the history is complete."""
    tx, ux = read_columns(case / HISTORY_X, 1)
    ty, uy = read_columns(case / HISTORY_Y, 2)
    delta_t = spec["period"] / spec["steps"]
    n_steps = spec["steps"] * spec["periods"]
    end_time = n_steps * delta_t
    for times in (tx, ty):
        if len(times) < n_steps or abs(times[-1] - end_time) > 0.5 * delta_t:
            fail(f"Truncated history in {case}: {len(times)} samples up to "
                 f"t = {times[-1] if times else 'none'}, expected {n_steps} "
                 f"up to t = {end_time:.6g}")
    if tx != ty:
        fail(f"Mismatched history times in {case}")
    return tx, [0.5 * (a - b) for a, b in zip(ux, uy)]


def linear_fit(x: list[float], y: list[float]) -> tuple[float, float]:
    n = len(x)
    mean_x, mean_y = sum(x) / n, sum(y) / n
    sxx = sum((a - mean_x) ** 2 for a in x)
    sxy = sum((a - mean_x) * (b - mean_y) for a, b in zip(x, y))
    slope = sxy / sxx
    return slope, mean_y - slope * mean_x


def frequency_and_damping(times: list[float], values: list[float],
                          periods: int) -> dict:
    """Damped frequency from a straight-line fit to the zero-crossing times
    (the zero crossings of a damped sinusoid are exactly half a damped period
    apart), and the decay rate from the peaks."""
    crossings = []
    for i in range(len(values) - 1):
        a, b = values[i], values[i + 1]
        if a == 0.0 or a * b < 0.0:
            crossings.append(times[i] + a / (a - b) * (times[i + 1] - times[i]))
    # Skip the first crossing, which the start-up transient can perturb
    crossings = crossings[1:]
    expected = 2 * periods - 2
    if len(crossings) < expected:
        fail(f"Found {len(crossings)} zero crossings, expected at least "
             f"{expected}")
    half_period, _ = linear_fit(list(range(len(crossings))), crossings)
    omega = math.pi / half_period
    residual = max(
        abs(t - (crossings[0] + k * half_period)) for k, t in enumerate(crossings)
    )
    if residual > 0.1 * half_period:
        fail("Zero crossings are not evenly spaced; the response is not a "
             "single-mode vibration")

    peaks = []
    for i in range(1, len(values) - 1):
        y0, y1, y2 = abs(values[i - 1]), abs(values[i]), abs(values[i + 1])
        same_sign = values[i] * values[i - 1] > 0 and values[i] * values[i + 1] > 0
        if same_sign and y1 >= y0 and y1 > y2 and times[i] > crossings[0]:
            curvature = y0 - 2 * y1 + y2
            shift = 0.5 * (y0 - y2) / curvature if curvature else 0.0
            peaks.append((times[i] + shift * (times[i + 1] - times[i]),
                          y1 - 0.25 * (y0 - y2) * shift))
    if len(peaks) < 2:
        fail("Too few peaks to measure the damping")
    slope, _ = linear_fit([p[0] for p in peaks], [math.log(p[1]) for p in peaks])
    decay = -slope
    period = 2 * math.pi / omega
    return {
        "omega": omega,
        "amplitude": peaks[0][1],
        "decay_rate": decay,
        "damping_ratio": decay / math.hypot(decay, omega),
        "loss_per_period": 1 - math.exp(-decay * period),
    }


def coupling_iterations(case: Path) -> tuple[float, int]:
    path = case / RESIDUALS
    if not path.is_file():
        return math.nan, 0
    per_step: dict[str, int] = {}
    for line in path.read_text(errors="replace").splitlines()[1:]:
        fields = line.split()
        if len(fields) >= 2:
            per_step[fields[0]] = max(per_step.get(fields[0], 0), int(fields[1]))
    if not per_step:
        return math.nan, 0
    counts = list(per_step.values())
    return sum(counts) / len(counts), max(counts)


def execution_time(case: Path) -> float:
    matches = re.findall(r"^ExecutionTime = ([0-9.eE+-]+) s",
                         (case / "log.solids4Foam").read_text(errors="replace"),
                         re.MULTILINE)
    return float(matches[-1]) if matches else math.nan


def analyse(spec: dict) -> dict:
    case = WORK_ROOT / spec["name"]
    times, values = read_histories(case, spec)
    row = dict(spec)
    row.update(frequency_and_damping(times, values, spec["periods"]))
    row["error"] = row["omega"] / spec["omega_exact"] - 1
    row["mean_iterations"], row["max_iterations"] = coupling_iterations(case)
    row["execution_time"] = execution_time(case)
    return row


