def ignore_results(directory: str, names: list[str]) -> set[str]:
    """Skip run output and anything that is not part of the tutorial set-up,
    in particular time directories left by an earlier tutorial run."""
    ignored = set()
    for name in names:
        if (
            name in ("verification", "regressionTests", "postProcessing",
                     "dynamicCode", "case.foam")
            or name.startswith("processor")
            or name.startswith("log.")
            or name.endswith(".pdf")
            or is_time_directory(name)
        ):
            ignored.add(name)
        if name == "polyMesh" and Path(directory).name in ("fluid", "solid") \
                and Path(directory).parent.name == "constant":
            ignored.add(name)
    return ignored


def refine_mesh(path: Path, factor: int) -> None:
    """Multiply the in-plane block divisions, keeping the single axial cell."""
    text = path.read_text()

    def scale(match: re.Match[str]) -> str:
        counts = [int(value) for value in match.group(2).split()]
        if len(counts) != 3:
            fail(f"Unexpected block division tuple in {path}: {match.group(2)}")
        counts = [counts[0] * factor, counts[1] * factor, counts[2]]
        return match.group(1) + "(" + " ".join(str(v) for v in counts) + ")"

    text, count = re.subn(r"(hex\s+\([^)]*\)\s+)\(([^()]+)\)", scale, text)
    if count != 1:
        fail(f"Expected one block in {path}, found {count}")
    path.write_text(text)


def time_controls(control: Path, delta_t: float, n_steps: int) -> None:
    replace_entry(control, "deltaT", f"{delta_t:.12g}")
    replace_entry(control, "endTime", f"{n_steps * delta_t:.12g}")
    # Write the fields at the end only; the point displacements are written
    # every time step
    replace_entry(control, "writeInterval", str(n_steps))
    replace_entry(control, "timePrecision", "12")


