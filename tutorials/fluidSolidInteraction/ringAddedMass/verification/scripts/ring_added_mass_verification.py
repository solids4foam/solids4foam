def prepare_dry(case: Path, solid: str) -> None:
    """Assemble a solid-only case from the solid region of the tutorial."""
    source = case.parent / (case.name + ".source")
    if source.exists():
        shutil.rmtree(source)
    shutil.copytree(TUTORIAL, source, ignore=ignore_results)
    for sub in ("0", "constant", "system"):
        (case / sub).mkdir(parents=True)
    for name in ("D", "D_0", "D_0_0", "pointD"):
        shutil.copy(source / "0/solid" / name, case / "0" / name)
    for name in ("mechanicalProperties", "dynamicMeshDict", "g"):
        shutil.copy(source / "constant/solid" / name, case / "constant" / name)
    shutil.copy(source / f"constant/solid/solidProperties.{solid}",
                case / "constant/solidProperties")
    for name in ("fvSchemes", "fvSolution", "blockMeshDict", "decomposeParDict"):
        shutil.copy(source / "system/solid" / name, case / "system" / name)
    shutil.copy(source / "system/controlDict", case / "system/controlDict")
    physics = (source / "constant/physicsProperties").read_text()
    physics, count = re.subn(r"^type\s+fluidSolidInteraction;", "type    solid;",
                             physics, flags=re.MULTILINE)
    if count != 1:
        fail("Could not set the solid physics type")
    (case / "constant/physicsProperties").write_text(physics)
    (case / "Allrun").write_text(DRY_ALLRUN)
    (case / "Allrun").chmod(0o755)
    shutil.rmtree(source)


def case_name(spec: dict) -> str:
    parts = [spec["kind"]]
    if spec["kind"] == "wet":
        parts += [spec["level"], spec["coupling"]]
    parts += [spec["solid"], f"m{spec['factor']}", f"n{spec['steps']}",
              f"p{spec['periods']}"]
    return "_".join(parts)


def settings(spec: dict, reference: dict) -> dict:
    """Everything that defines a run, used to validate a reused case."""
    data = {k: v for k, v in spec.items() if k != "groups"}
    data["deltaT"] = spec["period"] / spec["steps"]
    data["nSteps"] = spec["steps"] * spec["periods"]
    data["material"] = reference["material"]
    data["geometry"] = reference["geometry"]
    data["fluid"] = reference["fluid"]
    if spec["kind"] == "wet":
        data["rhoFluid"] = reference["levels"][spec["level"]]["rhoFluid"]
    data["tutorialFiles"] = tutorial_signature()
    data["build"] = build_signature()
    return data


def build_signature() -> dict:
    """OpenFOAM version and the solids4foam executable and library, so that a
    run is not reused with a different or rebuilt solver."""
    signature = {key: os.environ.get(key, "")
                 for key in ("WM_PROJECT", "WM_PROJECT_VERSION", "WM_OPTIONS")}
    candidates = [shutil.which("solids4Foam")]
    libbin = os.environ.get("FOAM_USER_LIBBIN", "")
    if libbin:
        candidates += sorted(str(p) for p in Path(libbin).glob(
            "libsolids4FoamModels.*"))
    for candidate in candidates:
        if candidate:
            status = Path(candidate).stat()
            signature[candidate] = f"{status.st_size}:{status.st_mtime_ns}"
    return signature


_SIGNATURE: dict | None = None


def tutorial_signature() -> dict:
    """Content hashes of the tutorial files that define the runs."""
    global _SIGNATURE
    if _SIGNATURE is None:
        signature = {}
        for path in sorted(TUTORIAL.rglob("*")):
            relative = path.relative_to(TUTORIAL)
            top = relative.parts[0]
            # Only the files that define the runs
            if top not in ("0", "constant", "system", "Allrun") \
                    or "polyMesh" in relative.parts or path.is_dir():
                continue
            if path.is_symlink():
                signature[str(relative)] = "->" + str(path.readlink())
            else:
                signature[str(relative)] = hashlib.sha1(
                    path.read_bytes()).hexdigest()
        _SIGNATURE = signature
    return _SIGNATURE


def configure(case: Path, spec: dict, reference: dict) -> None:
    delta_t = spec["period"] / spec["steps"]
    n_steps = spec["steps"] * spec["periods"]
    if spec["kind"] == "dry":
        prepare_dry(case, spec["solid"])
        refine_mesh(case / "system/blockMeshDict", spec["factor"])
    else:
        shutil.copytree(TUTORIAL, case, symlinks=True, ignore=ignore_results)
        refine_mesh(case / "system/solid/blockMeshDict", spec["factor"])
        refine_mesh(case / "system/fluid/blockMeshDict", spec["factor"])
        rho = reference["levels"][spec["level"]]["rhoFluid"]
        replace_entry(case / "constant/fluid/transportProperties", "rho",
                      f"rho [1 -3 0 0 0 0 0] {rho:.12g}")
    time_controls(case / "system/controlDict", delta_t, n_steps)


def solver_completed(case: Path) -> bool:
    log = case / "log.solids4Foam"
    return log.is_file() and bool(
        re.search(r"^End\s*$", log.read_text(errors="replace"), re.MULTILINE)
    )


def run_case(spec: dict, reference: dict, reuse: bool) -> str:
    case = WORK_ROOT / spec["name"]
    wanted = settings(spec, reference)
    stored = case / SETTINGS_FILE
    if reuse and case.is_dir():
        previous = None
        if stored.is_file():
            try:
                previous = json.loads(stored.read_text())
            except json.JSONDecodeError:
                previous = None
        if previous == wanted and solver_completed(case):
            try:
                read_histories(case, spec)
                return f"{spec['name']}: reusing the completed run"
            except RuntimeError as error:
                print(f"{spec['name']}: not reused ({error})")
        else:
            print(f"{spec['name']}: cached run does not match the requested "
                  "settings or did not finish; running it again")
    if case.exists():
        shutil.rmtree(case)
    configure(case, spec, reference)
    stored.write_text(json.dumps(wanted, indent=2, sort_keys=True))

    command = ["./Allrun"]
    if spec["kind"] == "wet":
        command += [spec["coupling"], spec["solid"]]
    log = case / "log.Allverify"
    with log.open("w") as handle:
        result = subprocess.run(command, cwd=case, stdout=handle,
                                stderr=subprocess.STDOUT, text=True)
    solver_log = case / "log.solids4Foam"
    if not solver_log.is_file():
        fail(f"{spec['name']} did not run the solver; see {log}")
    text = solver_log.read_text(errors="replace")
    if re.search(r"FOAM FATAL|FOAM aborting", text):
        fail(f"{spec['name']} failed; see {solver_log}")
    if not re.search(r"^End\s*$", text, re.MULTILINE):
        fail(f"{spec['name']} did not run to completion; see {solver_log}")
    if result.returncode:
        # The tutorial Allrun only fails after the solver when plotting
        print(f"{spec['name']}: Allrun returned {result.returncode} after the "
              f"solver completed; see {log}")
    return f"{spec['name']}: completed"


