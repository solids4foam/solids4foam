def observed_order(values: list[float], ratio: float = 2.0) -> float:
    """Order from three values at a constant refinement ratio."""
    d1, d2 = values[0] - values[1], values[1] - values[2]
    if d1 == 0 or d2 == 0 or d1 * d2 < 0:
        return math.nan
    return math.log(abs(d1 / d2)) / math.log(ratio)


def find(rows: list[dict], **keys) -> dict | None:
    for row in rows:
        if all(row.get(k) == v for k, v in keys.items()):
            return row
    return None


def add_ratios(rows: list[dict], reference: dict) -> None:
    exact = reference["exact"]["levels"]
    for row in rows:
        if row["kind"] != "wet":
            continue
        dry = find(rows, kind="dry", solid=row["solid"], factor=row["factor"],
                   steps=row["steps"], periods=row["periods"])
        if dry is None:
            continue
        row["ratio"] = row["omega"] / dry["omega"]
        row["ratio_error"] = row["ratio"] / exact[row["level"]]["ratio"] - 1
        row["ratio_thin_error"] = (
            row["ratio"] / exact[row["level"]]["ratioThinRing"] - 1
        )


def pct(value: float) -> str:
    return "–" if value is None or not math.isfinite(value) else f"{100 * value:+.3f}%"


def num(value: float, fmt: str = ".5f") -> str:
    return "–" if value is None or not math.isfinite(value) else format(value, fmt)


def check_rows(rows: list[dict], reference: dict, args: argparse.Namespace,
               lines: list[str]) -> list[str]:
    tol = reference["tolerances"]
    study = reference["study"]
    failures: list[str] = []
    levels = sorted({r["level"] for r in rows if r["kind"] == "wet"},
                    key=list(reference["levels"]).index)
    orders = ["", "## Observed orders", "",
              "| Series | Values | Order |", "|---|---|---:|"]

    def check(condition: bool, message: str) -> None:
        lines.append(f"- {'PASS' if condition else 'FAIL'}: {message}")
        if not condition:
            failures.append(message)

    def record(series: str, values: list[float]) -> float:
        order = observed_order(values)
        orders.append(f"| {series} | {', '.join(f'{v:.6g}' for v in values)} "
                      f"| {num(order, '.2f')} |")
        return order

    for row in rows:
        if row["loss_per_period"] < -tol["maxGrowthPerPeriod"]:
            check(False, f"{row['name']}: the amplitude grows by "
                  f"{pct(-row['loss_per_period'])} per period")

    if args.quick:
        quick = tol["quick"]
        for row in rows:
            check(abs(row["error"]) <= quick["omega"],
                  f"{row['name']}: frequency error {pct(row['error'])} within "
                  f"{100 * quick['omega']:.1f}%")
        return failures

    series_keys = [("dry", {"kind": "dry"})] + [
        (level, {"kind": "wet", "level": level, "coupling": "iqnils"})
        for level in levels
    ]
    factors = study["meshFactors"]
    steps = study["stepsPerPeriod"]

    main = [r for r in rows if "main" in r["groups"]]
    for label, keys in series_keys if main else []:
        series = [find(main, solid="highOrder", factor=f, steps=steps, **keys)
                  for f in factors]
        if any(s is None for s in series):
            continue
        finest = series[-1]
        check(abs(finest["error"]) <= tol["omega"],
              f"{label}: finest-mesh frequency error {pct(finest['error'])} "
              f"within {100 * tol['omega']:.2f}%")
        # The high-order solid is converged in space on the coarsest mesh,
        # so the mesh changes are at the level of the measurement noise and
        # have no meaningful order; they must stay small
        omegas = [s["omega"] for s in series]
        record(f"{label}: frequency, high-order solid, mesh", omegas)
        change = max(abs(omegas[i + 1] / omegas[i] - 1)
                     for i in range(len(omegas) - 1))
        check(change <= tol["meshChange"],
              f"{label}: largest mesh change in the frequency "
              f"{100 * change:.3f}% within {100 * tol['meshChange']:.2f}%")
        if label != "dry":
            ratios = [s["ratio_error"] for s in series]
            order = record(f"{label}: wet/dry ratio error, mesh", ratios)
            check(abs(finest["ratio_error"]) <= tol["ratio"],
                  f"{label}: finest-mesh wet/dry ratio error "
                  f"{pct(finest['ratio_error'])} within "
                  f"{100 * tol['ratio']:.2f}%")
            check(abs(ratios[-1]) < abs(ratios[0]),
                  f"{label}: the wet/dry ratio error decreases with mesh "
                  f"refinement ({pct(ratios[0])} to {pct(ratios[-1])})")
            check(abs(finest["ratio_thin_error"]) <= tol["ratioThinRing"],
                  f"{label}: finest-mesh ratio against thin-ring theory "
                  f"{pct(finest['ratio_thin_error'])} within "
                  f"{100 * tol['ratioThinRing']:.2f}%")
        time_series = [find(main, solid="highOrder",
                            factor=study["timeStudyFactor"], steps=n, **keys)
                       for n in study["timeSteps"]]
        if any(s is None for s in time_series):
            continue
        omegas = [s["omega"] for s in time_series]
        order = record(f"{label}: frequency, time step", omegas)
        check(math.isfinite(order) and order >= tol["minTimeOrder"],
              f"{label}: observed time order {num(order, '.2f')} at least "
              f"{tol['minTimeOrder']}")
        # Second-order Richardson extrapolation from the two smallest steps
        extrapolated = omegas[-1] + (omegas[-1] - omegas[-2]) / 3
        error = extrapolated / time_series[-1]["omega_exact"] - 1
        lines.append(f"  - {label}: time-extrapolated frequency "
                     f"{extrapolated:.6f} rad/s, error {pct(error)}")
        check(abs(error) <= tol["omegaExtrapolated"],
              f"{label}: time-extrapolated frequency error {pct(error)} "
              f"within {100 * tol['omegaExtrapolated']:.2f}%")
        loss = time_series[-1]["loss_per_period"]
        check(-tol["maxGrowthPerPeriod"] <= loss <= tol["maxLossPerPeriod"],
              f"{label}: amplitude loss {pct(loss)} per period at "
              f"{time_series[-1]['steps']} steps per period between "
              f"{-100 * tol['maxGrowthPerPeriod']:.1f}% and "
              f"{100 * tol['maxLossPerPeriod']:.1f}%")

    solid_rows = [r for r in rows if "solid" in r["groups"]]
    for label, keys in series_keys if solid_rows else []:
        series = [find(solid_rows, solid="standard", factor=f, steps=steps,
                       **keys) for f in factors]
        if any(s is None for s in series):
            continue
        order = record(f"{label}: frequency, standard solid, mesh",
                       [s["omega"] for s in series])
        check(math.isfinite(order) and order >= tol["minMeshOrder"],
              f"{label}: standard-solid observed mesh order "
              f"{num(order, '.2f')} at least {tol['minMeshOrder']}")
        if label != "dry":
            finest = series[-1]
            check(abs(finest["ratio_error"]) <= tol["ratio"],
                  f"{label}: standard-solid finest-mesh wet/dry ratio error "
                  f"{pct(finest['ratio_error'])} within "
                  f"{100 * tol['ratio']:.2f}% (frequency error "
                  f"{pct(finest['error'])})")

    coupling_rows = [r for r in rows if "coupling" in r["groups"]]
    for level in levels if coupling_rows else []:
        iq = find(coupling_rows, kind="wet", level=level, coupling="iqnils")
        rb = find(coupling_rows, kind="wet", level=level, coupling="robin")
        if iq is None or rb is None:
            continue
        check(abs(rb["omega"] / iq["omega"] - 1) <= tol["couplingAgreement"],
              f"{level}: Robin and IQN-ILS frequencies agree to "
              f"{pct(rb['omega'] / iq['omega'] - 1)} (within "
              f"{100 * tol['couplingAgreement']:.2f}%); mean coupling "
              f"iterations per step {num(iq['mean_iterations'], '.2f')} "
              f"(IQN-ILS) and {num(rb['mean_iterations'], '.2f')} (Robin)")
    if len(orders) > 5:
        lines += orders
    return failures


def table(rows: list[dict]) -> list[str]:
    out = [
        "| Case | ω (rad/s) | Exact | Error | Ratio | Ratio error | "
        "Thin-ring ratio error | Loss/period | Iter./step | Time (s) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        out.append(
            f"| {r['name']} | {num(r['omega'])} | {num(r['omega_exact'])} | "
            f"{pct(r['error'])} | {num(r.get('ratio', math.nan))} | "
            f"{pct(r.get('ratio_error', math.nan))} | "
            f"{pct(r.get('ratio_thin_error', math.nan))} | "
            f"{pct(r['loss_per_period'])} | "
            f"{num(r['mean_iterations'], '.2f')} | "
            f"{num(r['execution_time'], '.0f')} |"
        )
    return out


def write_csv(path: Path, rows: list[dict]) -> None:
    fields = ["name", "kind", "level", "coupling", "solid", "factor", "steps",
              "periods", "omega", "omega_exact", "error", "ratio",
              "ratio_error", "ratio_thin_error", "amplitude", "decay_rate",
              "damping_ratio", "loss_per_period", "mean_iterations",
              "max_iterations", "execution_time"]
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--study", choices=("all", "main", "solid", "coupling"),
                        default="all",
                        help="main: high-order solid mesh and time-step studies; "
                        "solid: standard against high-order solid; coupling: "
                        "IQN-ILS against Robin-Neumann (default: all)")
    parser.add_argument("--levels",
                        help="comma-separated added-mass levels (default: all)")
    parser.add_argument("--cores", type=int, default=1,
                        help="number of serial cases run at the same time")
    parser.add_argument("--reuse", action="store_true",
                        help="reuse completed runs under verification/work whose "
                        "settings match")
    parser.add_argument("--quick", action="store_true",
                        help="short smoke run on the coarsest mesh")
    args = parser.parse_args()
    if args.cores < 1:
        parser.error("--cores must be a positive integer")
    for executable in ("blockMesh", "solids4Foam"):
        if shutil.which(executable) is None:
            fail(f"Required executable '{executable}' is unavailable. "
                 "Source OpenFOAM and build solids4foam first.")
    reference = json.loads(REFERENCE_FILE.read_text())
    specs = build_specs(args, reference)
    WORK_ROOT.mkdir(parents=True, exist_ok=True)
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)

    print(f"Running {len(specs)} cases, {args.cores} at a time")
    errors = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.cores) as pool:
        futures = {pool.submit(run_case, spec, reference, args.reuse): spec
                   for spec in specs}
        for future in concurrent.futures.as_completed(futures):
            try:
                print(future.result(), flush=True)
            except RuntimeError as error:
                errors.append(str(error))
                print(f"ERROR: {error}", flush=True)

    rows = []
    for spec in specs:
        try:
            rows.append(analyse(spec))
        except RuntimeError as error:
            if not any(spec["name"] in e for e in errors):
                errors.append(f"{spec['name']}: {error}")
    add_ratios(rows, reference)
    rows.sort(key=lambda r: (r["kind"] != "dry",
                             list(reference["levels"]).index(r["level"])
                             if r["level"] else -1,
                             r["coupling"], r["solid"], r["factor"], r["steps"]))

    lines = ["# ringAddedMass verification summary", ""]
    lines += table(rows)
    lines += ["", "## Checks", ""]
    failures = check_rows(rows, reference, args, lines)
    for error in errors:
        lines.append(f"- FAIL: {error}")
    failures += errors
    lines += ["", "PASSED" if not failures else f"FAILED ({len(failures)} checks)"]
    summary = OUTPUT_ROOT / "verification_summary.md"
    summary.write_text("\n".join(lines) + "\n")
    write_csv(OUTPUT_ROOT / "ringAddedMass_results.csv", rows)
    print("\n".join(lines))
    print(f"\nWrote {summary}")
    return 0 if not failures else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (RuntimeError, subprocess.SubprocessError, OSError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(2)
