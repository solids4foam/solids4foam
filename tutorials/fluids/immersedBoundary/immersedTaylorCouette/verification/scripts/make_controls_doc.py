#!/usr/bin/env python3
"""Write controls.md of the immersedTaylorCouette verification from the tracked
control results (reference/results/controls/). The tables are generated; the
statements are checked by test_taylor_couette_controls.py against the same data.

Usage: python3 scripts/make_controls_doc.py [--check]
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import taylor_couette_controls as tc  # noqa: E402

DOC = Path(__file__).resolve().parent.parent / "controls.md"
NAMES = {("cutLink", "ME"): "cutLink, momentum exchange", ("cutLink", "ST"): "cutLink, surface traction",
         ("penalty", ""): "penalty", ("incremental", ""): "legacy incremental",
         ("ghostCell", ""): "ghostCell (exploratory)"}


def pct(x):
    return "" if x in ("", None) else f"{100 * float(x):+.2f}"


def table(head, rows):
    cells = [[str(c) for c in head]] + [[str(c) for c in r] for r in rows]
    width = [max(len(r[k]) for r in cells) for k in range(len(head))]
    line = lambda r: "| " + " | ".join(c.ljust(w) for c, w in zip(r, width)) + " |"
    return "\n".join([line(cells[0]), "| " + " | ".join("-" * w for w in width) + " |"] + [line(r) for r in cells[1:]])


def timestep_md():
    rows = []
    for r in tc.read_rows(tc.CONTROLS / "timestep-table.csv"):
        rows.append([NAMES[(r["method"], r["estimator"])], r["level"], pct(r["tutorial_error"])]
                    + [pct(r[f"error_cap_{c:g}"]) for c in tc.CAPS]
                    + [f"{100 * float(r['last_change']):+.2f}", f"{100 * float(r['last_change_over_error']):.0f}",
                       r["temporal_change_small"]])
    return table(["Method", "Level", "Tutorial step (%)", "Cap 0.01 (%)", "Cap 0.005 (%)", "Cap 0.0025 (%)",
                  "Cap 0.00125 (%)", "Last halving (points)", "Change / error (%)", "Change < 10 %"], rows)


def spatial_md():
    rows = []
    for r in tc.read_rows(tc.CONTROLS / "spatial-table.csv"):
        errs = [pct(r[f"error_L{i}"]) if r.get(f"error_L{i}") else "" for i in (1, 2, 3, 4)]
        rows.append([NAMES[(r["method"], r["estimator"])], f"{float(r['cap']):g}"] + errs
                    + [r["rates"], r["temporal_change_small_on_all"], r["all_steady"], r["statement"]])
    return table(["Method", "Cap (s)", "L1 (%)", "L2 (%)", "L3 (%)", "L4 (%)", "Rates between levels",
                  "Time change small on all", "All steady", "Statement"], rows)


def steady_md():
    rows = []
    for r in sorted(tc.read_rows(tc.CONTROLS / "steady-extended.csv"), key=lambda r: r["case"]):
        rows.append([r["case"].replace("TC-", "").replace("-np1", ""), r["T_8_10"], r["T_13_15"], r["T_18_20"],
                     r["drift_13_15_to_18_20"], r["dU_15_20"], "yes" if r["steady_by_criterion"] == "1" else "no"])
    return table(["Case", "T/Te, 8-10 s", "13-15 s", "18-20 s", "Drift 13-15 to 18-20 s", "Velocity change 15-20 s",
                  "Steady (< 1e-3)"], rows)


def audit_md():
    rows = [[r["level"], r["thinned_points"], r["solver_surface_traction_pct"], r["recipe_numerical_field_pct"],
             r["recipe_exact_field_circle_wall_pct"], r["recipe_exact_field_polygon_wall_pct"],
             r["first_fluid_layer_replaced_by_exact_pct"]]
            for r in tc.read_rows(tc.CONTROLS / "st-audit.csv")]
    return table(["Level", "Thinned points", "Solver (%)", "Recipe, numerical field (%)",
                  "Recipe, exact field, circle wall (%)", "Recipe, exact field, polygon wall (%)",
                  "Exact field in the first fluid layer only (%)"], rows)


TEMPLATE = """# Controls: mesh, time step, estimator and steady state (immersed Taylor-Couette)

<!-- markdownlint-disable MD013 -->

The tutorial step is limited by the Courant number and halves with every mesh
level (mean 0.095, 0.049, 0.025 and 0.013 s on Levels 1-4), so the tutorial
rows of `results.md` combine the mesh and the time step. The control runs
below use a `maxDeltaT` cap (a step that is constant after the start-up ramp,
checked on the written times) to separate them. The tracked rows are in
`reference/results/controls/`; the tables of this file are generated by
`scripts/make_controls_doc.py` and checked by a test. Torque errors are
(T - T_exact)/T_exact. The controls were run with the frozen build of
`results.md` and no solver change; the tutorial rows are reproduced exactly by
the export.

## Findings

1. **cutLink, momentum exchange** is insensitive to the time step on every
   level (the last halving changes the error by 7 %, 6 %, 1.5 % and 0.14 % of
   the error on Levels 1-4) and is steady. At a fixed cap of 0.01 s and 0.005 s
   the error falls from +0.91 % to +0.10 % over the four levels: an observed
   rate of 1.1 (successive rates 1.11, 0.94 and 1.17; 1.13, 0.98 and 1.19). This
   is the only spatial rate in this study that meets the pre-set conditions, and
   it is an observation on four levels, not a proven order.
2. **cutLink, surface traction.** The deficit does not depend on the time step
   (the last halving changes it by 6 %, 1.5 % and 0.12 % on Levels 1-3 and the
   audit gives -3.1 % on Level 4 with the capped-step fields) and does not
   decrease with the mesh. The audit table shows that the deficit comes from
   the numerical velocity in the first fluid layer next to the interface: the
   same recipe on the exact velocity converges (-0.97, -0.28, -0.08 and
   -0.02 % with a circle wall) and replacing only the first layer by the exact
   velocity removes most of the deficit. What inside `cutLink` produces that
   velocity error was not separated, and the solver was not changed.
3. **penalty** is time-converged on Levels 1 and 2 (the last halving changes
   the error by 0.2 % and 0.15 %; both are steady to 20 s) at -13.4 % and
   -7.0 %, but not on Levels 3 and 4: the error moves from -10.0 % at the
   tutorial step to -3.6 % at a cap of 0.00125 s on Level 3, and from -5.8 % at
   the tutorial step to -3.1 % at 0.00125 s on Level 4 (-5.6, -4.9, -4.1 and
   -3.1 % at the caps 0.01 to 0.00125 s), and the last halving still changes it
   by 21 % and 30 % of the error. On Level 4 each halving of the cap removes
   more of the deficit than the one before (0.66, 0.82 and 0.95 points), so no
   temporal limit is in sight. At the common cap of 0.00125 s the Level 3 and
   Level 4 errors (-3.6 % and -3.1 %) differ by 0.5 points, less than the
   change from either level's last halving. The tutorial step therefore
   overstates the torque deficit of this method on the fine meshes by an
   amount that is larger than the mesh effect between Levels 3 and 4. No
   temporal limit and no spatial rate is stated for it, and what in the
   penalty formulation produces the step dependence was not investigated.
4. **legacy incremental** does not converge with the step. On Level 2 it is
   steady and its torque is +7.1 % to +7.9 % for caps of 0.01 to 0.0025 s
   (last change 1.8 %), whereas the tutorial step gives +0.24 %. On Levels 1, 3
   and 4 the error keeps rising as the step is halved (the last change is
   43 %, 11 % and 44 % of the error) and the capped runs of Level 1 do not reach
   a steady torque. The agreement of the tutorial rows with the exact torque is
   therefore a coincidence of the mesh and the step, not a sign of convergence.
   The cause was not investigated further.
5. **ghostCell** (exploratory) has a time change below 10 % only on Level 3
   (8 %); on Levels 1 and 2 the error grows as the step is halved and on Level 4
   it passes through zero. No rate is stated.
6. **Steady state.** Runs to 20 s show that penalty on Levels 1 and 2,
   ghostCell on Level 1 and incremental on Level 2 are steady by the criterion
   of `results.md` (drift and velocity change below 1e-3), so their 10 s means
   are unchanged. The capped incremental runs on Level 1 are not steady (drift
   up to 7e-3). The criterion was not relaxed.

## Time-step study

Torque error at the tutorial step and at four caps; "Last halving" is the
change in the error at the last cap pair that was run.

__TIMESTEP__

## Mesh study at fixed step cap

A rate is stated only if the time change is small on every mesh involved, the
errors decrease monotonically and the successive rates agree within 0.3.

__SPATIAL__

## Steady-state extension to 20 s

The torque windows are the means of T/T_exact over the stated time windows.

__STEADY__

## Surface-traction audit

The recipe is the solver's: the mid-plane cut of the rotor STL, thinning to
0.7 of the mean cell width, a weighted quadratic fit within three cell
widths, the tangential viscous traction plus the pressure. Column 3 is the
solver, column 4 is the recipe on the numerical field (it reproduces the solver
to 0.04 points or better), and columns 5-7 replace the field by the exact one.
The torque from the exact stress on the polygon does not vanish because the
polygon (256 sides) is not the circle.

__AUDIT__

## Reproducing the control data

Every file of `reference/results/controls/` has a generator in this tree. The
runs are opt-in (none is part of CI) and each needs OpenFOAM.com; the costs are
the observed allocated rank-hours of the tracked runs.

<!-- markdownlint-disable MD013 -->

| File | Generated by | Cost |
| ---- | ------------ | ---- |
| `cases-timestep.csv`, Levels 1-2 and Level 3 at 0.01 and 0.005 s | `./Allverify run --runs dt`, then `analyse` | about 9 serial hours (these rows are in `reference/results/cases.csv`) |
| `cases-timestep.csv`, the 15 rows of the file | `./Allverify run --runs dt-extended`, then `analyse` | 35 rank-h (Level 4 on four ranks: 31 of them; the momentum exchange at 0.005 s alone is 5.6) |
| `steady-extended.csv`, `history-extended.csv` | `./Allverify run --runs steady20`, then `python3 scripts/taylor_couette_steady.py` (`--history-out` for the history) | about 2 serial hours (15 cases) |
| `st-audit.csv` | `./Allverify run --runs st-audit`, then `python3 scripts/taylor_couette_st_audit.py` (the two exact-field columns need no run) | 2.8 rank-h (Level 4: 2.5 on four ranks) |
| `timestep-table.csv`, `spatial-table.csv` | `python3 scripts/taylor_couette_controls.py all` | seconds, from the CSV files above |

<!-- markdownlint-enable MD013 -->

Not regenerated by this tree: `reference/results/history-*.csv`,
`profiles-L*.csv` and `scaling.csv` are exports of the complete runs written by
scripts that are not in the tree (the profiles bin the azimuthal velocity in
radial bins of half a cell width and the histories are the written rotor
torque); `analyse` writes only `work/results.csv`. The tracked rows come from
single runs of one build on a shared node: a rerun reproduces them only to
the `check` tolerances of the README (the time step is adaptive and the solver
tolerances are loose), and Level 4 is the only place where a different
decomposition changes the last digits.

## Figures

Figures are in `images/` as PNG and PDF: `controls_torque_vs_mesh`,
`controls_torque_vs_dt`, `controls_velocity_mesh`, `controls_estimators`,
`controls_steady` and `controls_histories`, produced by
`scripts/plot_controls.py`.

## Limits

- The step cap is constant after the ramp, so a cap of 0.01 s is already finer
  than the tutorial step on every level; the tutorial step itself is not in the
  cap series.
- The 0.00125 s cap exists only for penalty on Levels 3 and 4; the other Level 4
  series stop at 0.0025 s (0.005 s for cutLink and ghostCell).
- Conclusions about convergence rates and temporal limits are stated only where
  the pre-set conditions hold; everything else is a trend.
"""


def build():
    return (TEMPLATE.replace("__TIMESTEP__", timestep_md()).replace("__SPATIAL__", spatial_md())
            .replace("__STEADY__", steady_md()).replace("__AUDIT__", audit_md()))


def main(argv=None):
    text = build()
    if "--check" in (argv or sys.argv[1:]):
        return 0 if DOC.read_text() == text else 1
    DOC.write_text(text)
    print(f"written {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
