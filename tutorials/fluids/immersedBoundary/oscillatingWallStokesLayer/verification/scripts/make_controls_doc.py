#!/usr/bin/env python3
"""Write controls.md of the oscillatingWallStokesLayer verification from the
tracked control results (reference/results/controls/). The tables are
generated; the statements are checked by test_stokes_controls.py.

Usage: python3 scripts/make_controls_doc.py [--check]
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import stokes_controls as sc  # noqa: E402

DOC = Path(__file__).resolve().parent.parent / "controls.md"
LABEL = {"cutLink": "cutLink", "penalty": "penalty", "incremental": "legacy incremental",
         "ghostCell": "ghostCell (exploratory)"}
QNAME = {"u_L2_all_ivp": "velocity L2 / U0", "shear_amp_err_ivp": "shear amplitude error",
         "shear_rms_err_ivp": "shear RMS error"}


def g(x, n=3):
    return "" if x in ("", None) else f"{float(x):.{n}g}"


def table(head, rows):
    cells = [[str(c) for c in head]] + [[str(c) for c in r] for r in rows]
    width = [max(len(r[k]) for r in cells) for k in range(len(head))]
    line = lambda r: "| " + " | ".join(c.ljust(w) for c, w in zip(r, width)) + " |"
    return "\n".join([line(cells[0]), "| " + " | ".join("-" * w for w in width) + " |"] + [line(r) for r in cells[1:]])


def temporal_md():
    rows = []
    for r in sc.read_rows(sc.CONTROLS / "temporal-convergence.csv"):
        if r["estimator"] == "ST":
            continue
        rows.append([LABEL[r["method"]] + (" " + r["estimator"] if r["estimator"] else ""), r["level"],
                     QNAME[r["quantity"]], r["points"], g(r["dt_last"]), g(r["value_first"]), g(r["value_last"]),
                     g(r["last_difference"]), g(r["ratio"]), r["verdict"], g(r["limit"]), g(r["bound"])])
    return table(["Method", "Level", "Quantity", "Dt values", "Smallest dt (s)", "Value at 1e-3 s",
                  "Value at smallest dt", "Last difference", "Ratio", "Verdict", "Limit", "Bound"], rows)


def matched_md():
    rows = sc.merged_cases()
    out = []
    for method, est in (("cutLink", "ME"), ("cutLink", "FO"), ("penalty", ""), ("incremental", ""), ("ghostCell", "")):
        vals = []
        for lv in (1, 2, 3, 4):
            r = [x for x in rows if (x["method"], x["estimator"], int(x["level"])) == (method, est, lv)
                 and abs(float(x["dt"]) - 1.25e-4) < 1e-12]
            vals.append((g(r[0]["u_L2_all_ivp"], 3), f"{100 * float(r[0]['shear_amp_err_ivp']):+.2f}") if r else ("", ""))
        out.append([LABEL[method] + (" " + est if est else "")] + [x for p in vals for x in p])
    return table(["Method (dt = 1.25e-4 s)", "L1 velocity", "L1 amp. (%)", "L2 velocity", "L2 amp. (%)",
                  "L3 velocity", "L3 amp. (%)", "L4 velocity", "L4 amp. (%)"], out)


def offset_md():
    rows = [[r["case"], r["yw"], r["level"], g(r["predicted_offset_over_h"]), g(r["fitted_ME_over_h"]),
             g(r["diff_rms_ME"]), g(r["amp_err_ME"]), g(r["amp_err_FO"])]
            for r in sc.read_rows(sc.CONTROLS / "offset-audit.csv")]
    return table(["Case", "Wall y (m)", "Level", "Predicted offset / h", "Fitted offset / h",
                  "RMS(ME - FO) / exact RMS", "ME amplitude error", "Forcing amplitude error"], rows)


def cellavg_md():
    rows = [[r["level"], LABEL[r["method"]], g(r["centre"]), g(r["average"]), g(r["centre_whole"]),
             g(r["average_whole"])] for r in sc.read_rows(sc.CONTROLS / "cell-average.csv")]
    return table(["Level", "Method", "Centre", "Cell average", "Centre, whole cells", "Average, whole cells"], rows)


def regions_md():
    rows = [[r["method"], r["level"], r["dt"], g(r["L2_all"]), g(r["L2_interface_row"]), g(r["L2_near"]),
             g(r["L2_bulk"])] for r in sc.read_rows(sc.CONTROLS / "velocity-regions.csv")
            if r["level"] in ("3", "4")]
    return table(["Method", "Level", "dt (s)", "All rows", "Interface row", "Within one thickness",
                  "Bulk (s > delta)"], rows)


TEMPLATE = """# Controls: time step, wall position, comparison and plateau (Stokes layer)

<!-- markdownlint-disable MD013 -->

The tables are generated by `scripts/make_controls_doc.py` from
`reference/results/controls/` (rows of the control runs, with the tutorial rows
of `reference/results/cases.csv` reproduced exactly, 69 of 69) and checked by
`scripts/test_stokes_controls.py`. The controls vary the step from 1e-3 s to
as little as 3.1e-5 s, and put the wall on a mesh face; they were run with the
frozen build of `results.md` and no solver change. Errors are against the exact
solution of the simulated initial-value problem (`_ivp`) unless stated. The
velocity is the L2 error over the fluid rows divided by U0.

## Findings

1. **cutLink momentum exchange: the 3.1-3.2 % amplitude error is geometric.**
   Momentum exchange minus forcing equals rho times the slab acceleration times
   the distance between the wall and the nearest mesh face, to three digits
   (fitted offsets 0.062, 0.127, 0.255 and -0.487 of a cell width against 0.064,
   0.128, 0.256 and -0.488 on Levels 1-4; the sign change on Level 4 follows
   from the position of the wall). With the wall moved onto a mesh face (a
   controlled run on Levels 2-4, only the top vertices of the slab changed) the
   difference vanishes (fitted offset below 0.001 cell widths) and the ME
   amplitude error falls from 3.2 % to 2.2e-4, 8.7e-6 and 3.2e-5. This is a
   test of the cause, on three meshes. The forcing estimator is also slightly
   offset-dependent (0.20 % to 0.28 % on Level 2).
2. **The step does not change the cutLink velocity** (smallest change below
   3.7e-7 of U0 on Level 4 with five steps) nor its shear amplitude at the
   resolution of the table (saturated on Level 4), so the cutLink numbers of
   `results.md` are time-converged to the stated digits. The momentum exchange
   shear RMS error on Levels 1-3 grows by 3 % to 7 % between 1e-3 s and
   1.25e-4 s (first-order, bound about 4e-4).
3. **penalty** is time-converged in velocity on Levels 1-3 but not on Level 4
   at the tutorial step: 7.4e-3 at 1e-3 s against 4.08e-3 at 6.25e-5 s
   (saturated there; the tutorial step overstates the error by 1.8 times). The
   shear amplitude error of Level 4 (-3.5 % to -1.5 %) is still changing and no
   limit is stated for it.
4. **legacy incremental** has no monotone temporal limit on Level 4. Its
   velocity error passes through a minimum (6.0e-5 at 1.25e-4 s) and rises to
   1.7e-4 at 3.1e-5 s (last change 24 %), while the shear amplitude error
   falls from +4.5 % to +3.3 %. No floor is claimed: the data show a
   non-monotone series, not saturation. On Level 3 the velocity is saturated
   (7.5e-3).
5. **ghostCell** has a plateau of about 1e-3 on Levels 3 and 4 that does not
   depend on the step: 9.2e-4 (Level 3) and 1.1e-3 (Level 4) at the smallest
   step, increasing by at most 2.5e-5 per halving (extrapolated limits 9.3e-4 and
   1.1e-3). It is present in the bulk (3.1e-4 and 4.0e-4) and not only at the
   interface, and is not removed by the choice of comparison: at the tutorial
   step the exact cell average changes Level 3 from 8.1e-4 to 1.0e-3 and
   Level 4 from 7.0e-4 to 8.9e-4 (7.1e-4 on whole cells). The cause of the plateau was not isolated.
6. **Cell-centre against cell-average comparison.** The choice changes
   penalty, incremental and ghostCell by under 30 % (Levels 3-4), but changes
   the cutLink value on Level 4 from 6.2e-5 to 6.7e-4 if the cells cut by the
   wall are included, and not on whole cells (5.7e-5), so the cutLink velocity
   error is not a function of the comparison on the cells it resolves.
7. **No spatial rate is stated for the Stokes layer.** At a matched step of
   1.25e-4 s the penalty velocity errors give rates of 1.01, 1.22 and 1.38 (spread
   0.37, above the pre-set 0.3), and incremental, ghostCell and cutLink are
   limited by the offset, the plateau or a non-monotone step dependence, so
   the matched-step table below is a trend only.

## Time-step convergence

A series is converged to a bound only if three successive halvings give
monotone differences with ratio in [1.6, 2.5] (first order) or [3, 5] (second
order); a series with five or more steps whose last two changes are below 1 % is
labelled saturated.

__TEMPORAL__

## Matched step

__MATCHED__

## Wall position control

The offset is the distance between the wall and the nearest mesh face. The
predicted column is rho times that distance over the cell width; the fitted
column is the coefficient of the regression of ME minus forcing on the
acceleration of the slab.

__OFFSET__

## Velocity error by region

Levels 3 and 4 at the tutorial step and at 1.25e-4 s; "near" is within one
boundary-layer thickness of the wall, "bulk" beyond it.

__REGIONS__

## Cell centre against cell average

The second column of values compares with the exact average over each cell
(Gauss-Legendre, five points); "whole cells" keeps the rows whose cell is wholly
in the fluid.

__CELLAVG__

## Figures

`images/controls_dt_velocity`, `controls_dt_shear`, `controls_matched_dt`,
`controls_alignment`, `controls_ghost_regions`, `controls_offset` and
`controls_cellavg` (PNG and PDF), produced by `scripts/plot_controls.py`. The
`_al` columns of the tables are a post-processing diagnostic (the inertia
averaged over two steps to be centred at the force time) and are not used for
any claim above; the raw columns are always kept.

## Limits

- The wall-position control covers Levels 2-4, for the momentum exchange and the
  forcing estimator; Level 1 and the other methods were not rerun.
- The time series stop at 6.25e-5 s (3.1e-5 s for incremental on
  Levels 3-4), a factor of 16 to 32 below the tutorial step.
- The cause of the ghostCell plateau and of the penalty and incremental Level 4
  step dependence was not separated.
"""


def build():
    return (TEMPLATE.replace("__TEMPORAL__", temporal_md()).replace("__MATCHED__", matched_md())
            .replace("__OFFSET__", offset_md()).replace("__REGIONS__", regions_md())
            .replace("__CELLAVG__", cellavg_md()))


def main(argv=None):
    text = build()
    if "--check" in (argv or sys.argv[1:]):
        return 0 if DOC.read_text() == text else 1
    DOC.write_text(text)
    print(f"written {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
