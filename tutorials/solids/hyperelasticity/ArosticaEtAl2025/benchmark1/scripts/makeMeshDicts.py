#!/usr/bin/env python3
"""
Write system/blockMeshDict and system/extrudeMeshDict for the truncated
ellipsoid of Arostica et al. (2025), benchmark 1 (eq. 9-11 of the paper):

    x = ( r_long cos(mu), r_short sin(mu) cos(theta), r_short sin(mu) sin(theta) )

    endocardium: r_short = 25 mm, r_long = 90 mm, mu in [-pi, -acos(5/17)]
    epicardium : r_short = 35 mm, r_long = 97 mm, mu in [-pi, -acos(5/20)]

The long axis is x. The base (Gamma_top) is the straight line joining the endo
and epi base points, revolved: a shallow cone, not a plane, exactly as in the
reference gmsh script of the cardiac-benchmark-toolkit.

The mesh is built the same way as LandEtAl2015/problem3:
  1. blockMesh makes a single-cell-thick slice of the wall in the x-y plane
     (y >= 0 is the radial coordinate), with spline edges on endo and epi;
  2. extrudeMesh revolves the z = 0 face ("top") through 360 degrees about x;
  3. createPatch removes the leftover, now empty, patches.

Usage:
    python3 makeMeshDicts.py [level]      level 1 (coarse) ... 4 (fine), default 2
"""
import math
import sys

R_SHORT_ENDO, R_LONG_ENDO = 25.0, 90.0   # mm
R_SHORT_EPI, R_LONG_EPI = 35.0, 97.0     # mm
MU_BASE_ENDO = -math.acos(5.0 / 17.0)
MU_BASE_EPI = -math.acos(5.0 / 20.0)

# (cells apex->base along the wall, cells through the wall, cells around)
LEVELS = {
    1: (20, 3, 32),
    2: (40, 5, 64),
    3: (80, 10, 128),
    4: (160, 20, 256),
}

HEADER = r"""/*--------------------------------*- C++ -*----------------------------------*\
| solids4foam: solid mechanics and fluid-solid interaction simulations        |
| Version:     v2.4                                                           |
| Web:         https://solids4foam.github.io                                  |
| Disclaimer:  This offering is not approved or endorsed by OpenCFD Limited,  |
|              producer and distributor of the OpenFOAM software via          |
|              www.openfoam.com, and owner of the OPENFOAM® and OpenCFD®      |
|              trade marks.                                                   |
\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      %s;
}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
"""


def ellipse(mu, rs, rl):
    # Meridian in the x-y plane, y >= 0 (theta = pi in the paper's convention;
    # the body is axisymmetric so this is the same curve)
    return (rl * math.cos(mu), -rs * math.sin(mu))


def spline(mu0, mu1, rs, rl, z, n=100):
    pts = []
    for i in range(1, n):
        mu = mu0 + (mu1 - mu0) * i / n
        x, y = ellipse(mu, rs, rl)
        pts.append(f"            ({x:.9g} {y:.9g} {z:g})")
    return "\n".join(pts)


def block_mesh_dict(nWall, nTrans):
    epiBase = ellipse(MU_BASE_EPI, R_SHORT_EPI, R_LONG_EPI)
    epiApex = (-R_LONG_EPI, 0.0)
    endoApex = (-R_LONG_ENDO, 0.0)
    endoBase = ellipse(MU_BASE_ENDO, R_SHORT_ENDO, R_LONG_ENDO)
    quad = [epiBase, epiApex, endoApex, endoBase]
    # Slab: vertices 0-3 at z = 1 mm, vertices 4-7 at z = 0 (the patch that is
    # revolved). Same numbering as LandEtAl2015/problem3, so the hex below is
    # right-handed for the same reason
    v = [f"    ({p[0]:.9g} {p[1]:.9g} 1)" for p in quad] \
        + [f"    ({p[0]:.9g} {p[1]:.9g} 0)" for p in quad]
    s = HEADER % "blockMeshDict"
    s += f"""
// Generated by scripts/makeMeshDicts.py: {nWall} cells along the wall,
// {nTrans} through it

scale   0.001;

vertices
(
{chr(10).join(v)}
);

blocks
(
    hex (4 5 6 7 0 1 2 3) ({nWall} {nTrans} 1) simpleGrading (1 1 1)
);

edges
(
    // Epicardium, apex to base
    spline 1 0
    (
{spline(-math.pi, MU_BASE_EPI, R_SHORT_EPI, R_LONG_EPI, 1)}
    )
    spline 5 4
    (
{spline(-math.pi, MU_BASE_EPI, R_SHORT_EPI, R_LONG_EPI, 0)}
    )

    // Endocardium, apex to base
    spline 2 3
    (
{spline(-math.pi, MU_BASE_ENDO, R_SHORT_ENDO, R_LONG_ENDO, 1)}
    )
    spline 6 7
    (
{spline(-math.pi, MU_BASE_ENDO, R_SHORT_ENDO, R_LONG_ENDO, 0)}
    )
);

boundary
(
    // Gamma_top: the (conical) base, a spring-dashpot (Robin) condition
    base
    {{
        type patch;
        faces ((0 4 7 3));
    }}
    // The apex edge; it lies on the axis and vanishes on revolution
    right
    {{
        type patch;
        faces ((2 6 5 1));
    }}
    // Gamma_endo: the endocardium, loaded by the cavity pressure p(t)
    endo
    {{
        type patch;
        faces ((3 7 6 2));
    }}
    // Gamma_epi: the epicardium, a normal spring-dashpot (pericardium)
    epi
    {{
        type patch;
        faces ((1 5 4 0));
    }}
    // The z = 0 face, revolved by extrudeMesh
    top
    {{
        type patch;
        faces ((4 5 6 7));
    }}
    bottom
    {{
        type patch;
        faces ((0 3 2 1));
    }}
);

mergePatchPairs
(
);

// ************************************************************************* //
"""
    return s


def extrude_mesh_dict(nCirc):
    s = HEADER % "extrudeMeshDict"
    s += f"""
// Generated by scripts/makeMeshDicts.py: {nCirc} cells around the long axis

constructFrom patch;

sourceCase ".";
sourcePatches (top);

exposedPatchName top;

flipNormals true;

extrudeModel        sector;

nLayers             {nCirc};

expansionRatio      1;

sectorCoeffs
{{
    point       (0 0 0);
    axis        (1 0 0);
    angle       360;
}}

mergeFaces true;

mergeTol 1e-9;

// ************************************************************************* //
"""
    return s


def main():
    level = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    if level not in LEVELS:
        sys.exit(f"Unknown mesh level {level}; choose from {sorted(LEVELS)}")
    nWall, nTrans, nCirc = LEVELS[level]
    with open("system/blockMeshDict", "w") as fh:
        fh.write(block_mesh_dict(nWall, nTrans))
    with open("system/extrudeMeshDict", "w") as fh:
        fh.write(extrude_mesh_dict(nCirc))
    print(f"Mesh level {level}: {nWall} x {nTrans} x {nCirc} = "
          f"{nWall*nTrans*nCirc} cells")


if __name__ == "__main__":
    main()
